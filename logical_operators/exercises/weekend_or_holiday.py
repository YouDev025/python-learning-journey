# Print True if it is a weekend OR a holiday.
# ============================================================

is_holiday = True
is_weekend = True

print("is_holiday:", is_holiday)
print("is_weekend:", is_weekend)

print("\n--- Logical Operations ---")

print("Weekend AND Holiday:", is_weekend and is_holiday)
print("NOT Weekend AND NOT Holiday:", not is_weekend and not is_holiday)

print("Weekend OR Holiday:", is_weekend or is_holiday)
print("NOT Weekend OR NOT Holiday:", not is_weekend or not is_holiday)

print("Weekend AND NOT Holiday:", is_weekend and not is_holiday)
print("NOT Weekend AND Holiday:", not is_weekend and is_holiday)